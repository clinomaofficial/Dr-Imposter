const fs = require('fs');
const path = require('path');

const STAGING_FILE = path.join(__dirname, 'dahl_generated_25.json');

const WORDS_FILE = path.join(__dirname, '..', 'src', 'data', 'medicalWords.ts');
const HINTS_FILE = path.join(__dirname, '..', 'src', 'data', 'hints.ts');
const FLASHCARDS_FILE = path.join(__dirname, '..', 'src', 'data', 'soloFlashcards.ts');
const SOLOHINTS_FILE = path.join(__dirname, '..', 'src', 'data', 'soloHints.ts');

function cleanText(str) {
  if (!str) return '';
  return str
    .replace(/\*\*/g, '')
    .replace(/^\[(Rx|Dx|Sx|Etiology|Anatomy|Classification|Pearl)\]\s*/i, '')
    .trim();
}

function runIntegration() {
  if (!fs.existsSync(STAGING_FILE)) {
    console.error('Staging file not found:', STAGING_FILE);
    process.exit(1);
  }

  const rawData = JSON.parse(fs.readFileSync(STAGING_FILE, 'utf-8'));
  const termIds = Object.keys(rawData).sort();

  if (termIds.length < 25) {
    console.log(`Warning: only ${termIds.length} / 25 terms generated so far.`);
  }

  console.log(`Integrating ${termIds.length} terms generated by Dahl...`);

  // 1. Update medicalWords.ts
  let wordsContent = fs.readFileSync(WORDS_FILE, 'utf-8');
  let wordsAdded = 0;
  for (const id of termIds) {
    if (wordsContent.includes(`id: "${id}"`) || wordsContent.includes(`id: '${id}'`)) {
      continue; // already present
    }
    const item = rawData[id].word;
    const codeBlock = `  {\n    id: "${item.id}",\n    word: { Arabic: ${JSON.stringify(item.word.Arabic)}, English: ${JSON.stringify(item.word.English)} },\n    level: "${item.level}",\n    difficulty: ${item.difficulty},\n    type: "${item.type}",\n    subjects: ${JSON.stringify(item.subjects)},\n    synonyms: ${JSON.stringify(item.synonyms)},\n    guessingDifficulty: ${item.guessingDifficulty || item.difficulty}\n  },\n`;
    
    // Insert before "];\n\n// In-place dynamic enrichment"
    const targetIdx = wordsContent.search(/\];\r?\n\r?\n\/\/ In-place dynamic enrichment/);
    if (targetIdx !== -1) {
      wordsContent = wordsContent.slice(0, targetIdx) + codeBlock + wordsContent.slice(targetIdx);
      wordsAdded++;
    } else {
      console.error('Could not find insert anchor in medicalWords.ts');
    }
  }
  fs.writeFileSync(WORDS_FILE, wordsContent, 'utf-8');
  console.log(`✓ medicalWords.ts updated (+${wordsAdded} terms).`);

  // 2. Update hints.ts
  let hintsContent = fs.readFileSync(HINTS_FILE, 'utf-8');
  let hintsAdded = 0;
  for (const id of termIds) {
    if (hintsContent.includes(`"${id}": {`)) {
      continue;
    }
    const item = rawData[id].hints;
    const arClean = item.Arabic.map(cleanText);
    const enClean = item.English.map(cleanText);

    const hintBlock = `  "${id}": {\n    "Arabic": ${JSON.stringify(arClean, null, 6).replace(/\n/g, '\n  ')},\n    "English": ${JSON.stringify(enClean, null, 6).replace(/\n/g, '\n  ')}\n  },\n`;

    // Anchor: before "};\n\nfunction makeArabicClueEgyptianAndClean"
    const targetIdx = hintsContent.search(/\};\r?\n\r?\nfunction makeArabicClueEgyptianAndClean/);
    if (targetIdx !== -1) {
      hintsContent = hintsContent.slice(0, targetIdx) + hintBlock + hintsContent.slice(targetIdx);
      hintsAdded++;
    } else {
      console.error('Could not find insert anchor in hints.ts');
    }
  }
  fs.writeFileSync(HINTS_FILE, hintsContent, 'utf-8');
  console.log(`✓ hints.ts updated (+${hintsAdded} hint sets).`);

  // 3. Update soloFlashcards.ts
  let fcContent = fs.readFileSync(FLASHCARDS_FILE, 'utf-8');
  let fcAdded = 0;
  for (const id of termIds) {
    if (fcContent.includes(`"${id}": {`)) {
      continue;
    }
    const item = rawData[id].flashcard;
    const cleanFC = {
      Arabic: {
        etiology: cleanText(item.Arabic.etiology),
        goldStandard: cleanText(item.Arabic.goldStandard),
        firstLineRx: cleanText(item.Arabic.firstLineRx),
        keyDifferentiator: cleanText(item.Arabic.keyDifferentiator)
      },
      English: {
        etiology: cleanText(item.English.etiology),
        goldStandard: cleanText(item.English.goldStandard),
        firstLineRx: cleanText(item.English.firstLineRx),
        keyDifferentiator: cleanText(item.English.keyDifferentiator)
      }
    };

    const fcBlock = `  "${id}": ${JSON.stringify(cleanFC, null, 4).replace(/\n/g, '\n  ')},\n`;

    // Anchor: before "};\n\n/**\n * دالة استخراج بطاقة الفلاش كارد السريرية الشاملة"
    const targetIdx = fcContent.indexOf('};\n\n/**\n * دالة استخراج بطاقة الفلاش كارد السريرية الشاملة');
    if (targetIdx !== -1) {
      fcContent = fcContent.slice(0, targetIdx) + fcBlock + fcContent.slice(targetIdx);
      fcAdded++;
    } else {
      console.error('Could not find insert anchor in soloFlashcards.ts');
    }
  }
  fs.writeFileSync(FLASHCARDS_FILE, fcContent, 'utf-8');
  console.log(`✓ soloFlashcards.ts updated (+${fcAdded} debrief flashcards).`);

  // 4. Update soloHints.ts
  let shContent = fs.readFileSync(SOLOHINTS_FILE, 'utf-8');
  let shAdded = 0;
  for (const id of termIds) {
    if (shContent.includes(`"${id}": {`)) {
      continue;
    }
    const item = rawData[id].soloHint;
    const cleanSH = {
      Arabic: {
        hint1: cleanText(item.Arabic.hint1),
        hint2: cleanText(item.Arabic.hint2),
        hint3: cleanText(item.Arabic.hint3),
        pearl: cleanText(item.Arabic.pearl)
      },
      English: {
        hint1: cleanText(item.English.hint1),
        hint2: cleanText(item.English.hint2),
        hint3: cleanText(item.English.hint3),
        pearl: cleanText(item.English.pearl)
      }
    };

    const shBlock = `  "${id}": ${JSON.stringify(cleanSH, null, 4).replace(/\n/g, '\n  ')},\n`;

    // Anchor: before "};\n\n/**\n * دالة استخراج التلميحات التدريجية الثلاثة"
    const targetIdx = shContent.indexOf('};\n\n/**\n * دالة استخراج التلميحات التدريجية الثلاثة');
    if (targetIdx !== -1) {
      shContent = shContent.slice(0, targetIdx) + shBlock + shContent.slice(targetIdx);
      shAdded++;
    } else {
      console.error('Could not find insert anchor in soloHints.ts');
    }
  }
  fs.writeFileSync(SOLOHINTS_FILE, shContent, 'utf-8');
  console.log(`✓ soloHints.ts updated (+${shAdded} 3-tier solo hints).`);

  console.log('\n=== INTEGRATION COMPLETE ===');
}

runIntegration();
